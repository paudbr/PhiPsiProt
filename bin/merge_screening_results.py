#!/usr/bin/env python3

"""
Merge screening results into a final candidate table.

Purpose
-------
Combine ranked screening candidates with residue selection metadata.

Inputs
------
ranked_candidates.csv:
    Candidate ranking results generated by RANK_SCREENING.

selection_summary.csv:
    Metadata describing how mutable residues were selected.

Outputs
-------
final_screening_results.csv:
    Final screening table containing:
    - PyRosetta ddG results
    - biophysical annotations
    - ranking information
    - residue selection metadata

Notes
-----
This step does not modify candidate scores or rankings.
It only appends workflow metadata required for reporting and
downstream structural validation workflows.
"""

import argparse
import csv


parser = argparse.ArgumentParser()
parser.add_argument("--candidates", required=True)
parser.add_argument("--selection_summary", required=True)
parser.add_argument("--output", required=True)
args = parser.parse_args()


selection_metadata = {}

with open(args.selection_summary, newline="") as infile:
    reader = csv.DictReader(infile)
    for row in reader:
        selection_metadata = row
        break


extra_fields = [
    "selection_mode",
    "selected_positions",
    "ligand_resname",
    "interface_chain",
    "distance_cutoff",
    "pipeline_stage",
]

rows = []

with open(args.candidates, newline="") as infile:
    reader = csv.DictReader(infile)

    fieldnames = list(reader.fieldnames or [])

    for field in extra_fields:
        if field not in fieldnames:
            fieldnames.append(field)

    for row in reader:
        row["selection_mode"] = selection_metadata.get("selection_mode", "")
        row["selected_positions"] = selection_metadata.get("selected_positions", "")
        row["ligand_resname"] = selection_metadata.get("ligand_resname", "")
        row["interface_chain"] = selection_metadata.get("interface_chain", "")
        row["distance_cutoff"] = selection_metadata.get("distance_cutoff", "")
        row["pipeline_stage"] = "screening_ready_for_structural_validation"

        rows.append(row)


with open(args.output, "w", newline="") as outfile:
    writer = csv.DictWriter(outfile, fieldnames=fieldnames)
    writer.writeheader()
    writer.writerows(rows)


print(f"Final screening results written: {len(rows)}")