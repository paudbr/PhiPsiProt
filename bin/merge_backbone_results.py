#!/usr/bin/env python3

"""
===============================================================================
merge_backbone_results.py

Purpose:
Merge RFdiffusion backbone candidates with ProteinMPNN-designed sequences.

Inputs:
- candidates_csv:
    CSV generated by summarize_backbone_design.py

- mpnn_fastas:
    One or more FASTA files generated by ProteinMPNN

Outputs:
- output_csv:
    CSV file with one row per backbone-design sequence pair

Notes:
- One backbone can have one or more ProteinMPNN-designed sequences.
- Each designed sequence becomes one row in the merged output table.
- This allows num_seq_per_target > 1.
===============================================================================
"""

import argparse
import csv
from pathlib import Path


def parse_mpnn_fasta(fasta_path):
    """
    Parse a ProteinMPNN FASTA file and extract all designed sequences.

    ProteinMPNN FASTA files usually contain:
    - an initial native/input sequence entry
    - one or more designed sequences with headers starting with >T=

    This function keeps only designed sequences.
    """
    fasta_path = Path(fasta_path)
    candidate_id = fasta_path.stem

    designs = []
    lines = [x.strip() for x in fasta_path.read_text().splitlines() if x.strip()]

    design_index = 0

    for i, line in enumerate(lines):
        if not line.startswith(">T="):
            continue

        if i + 1 >= len(lines):
            continue

        designed_sequence = lines[i + 1]

        mpnn_score = "NA"
        global_score = "NA"
        seq_recovery = "NA"
        sample = design_index

        fields = line.replace(">", "").split(",")

        for field in fields:
            field = field.strip()

            if field.startswith("score="):
                mpnn_score = field.split("=", 1)[1]

            elif field.startswith("global_score="):
                global_score = field.split("=", 1)[1]

            elif field.startswith("seq_recovery="):
                seq_recovery = field.split("=", 1)[1]

            elif field.startswith("sample="):
                sample = field.split("=", 1)[1]

        designs.append({
            "candidate_id": candidate_id,
            "design_id": f"{candidate_id}_mpnn_{design_index}",
            "designed_sequence": designed_sequence,
            "mpnn_score": mpnn_score,
            "mpnn_global_score": global_score,
            "mpnn_seq_recovery": seq_recovery,
            "mpnn_sample": sample,
        })

        design_index += 1

    return candidate_id, designs


def main():
    parser = argparse.ArgumentParser(
        description="Merge RFdiffusion backbone candidates with ProteinMPNN results."
    )

    parser.add_argument("--candidates_csv", required=True)
    parser.add_argument("--mpnn_fastas", nargs="+", required=True)
    parser.add_argument("--output_csv", required=True)

    args = parser.parse_args()

    mpnn_by_candidate = {}

    for fasta in args.mpnn_fastas:
        candidate_id, designs = parse_mpnn_fasta(fasta)
        mpnn_by_candidate[candidate_id] = designs

    rows = []

    with open(args.candidates_csv, newline="") as infile:
        reader = csv.DictReader(infile)

        for row in reader:
            candidate_id = row["candidate_id"]
            designs = mpnn_by_candidate.get(candidate_id, [])

            if not designs:
                missing_row = dict(row)
                missing_row["design_id"] = f"{candidate_id}_mpnn_missing"
                missing_row["backbone_sequence"] = row.get("sequence", "NA")
                missing_row["designed_sequence"] = "NA"
                missing_row["final_sequence"] = "NA"
                missing_row["mpnn_score"] = "NA"
                missing_row["mpnn_global_score"] = "NA"
                missing_row["mpnn_seq_recovery"] = "NA"
                missing_row["mpnn_sample"] = "NA"
                missing_row["pipeline_stage"] = "proteinmpnn_missing"
                missing_row["status"] = "missing_proteinmpnn_design"
                rows.append(missing_row)
                continue

            for design in designs:
                merged_row = dict(row)
                merged_row["design_id"] = design["design_id"]
                merged_row["backbone_sequence"] = row.get("sequence", "NA")
                merged_row["designed_sequence"] = design["designed_sequence"]
                merged_row["final_sequence"] = design["designed_sequence"]
                merged_row["mpnn_score"] = design["mpnn_score"]
                merged_row["mpnn_global_score"] = design["mpnn_global_score"]
                merged_row["mpnn_seq_recovery"] = design["mpnn_seq_recovery"]
                merged_row["mpnn_sample"] = design["mpnn_sample"]
                merged_row["pipeline_stage"] = "backbone_ready_for_filtering"
                merged_row["status"] = "pending_filtering"
                rows.append(merged_row)

    if not rows:
        raise ValueError("No backbone candidates were found to merge.")

    fieldnames = list(rows[0].keys())

    with open(args.output_csv, "w", newline="") as out:
        writer = csv.DictWriter(out, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Merged {len(rows)} backbone design rows")


if __name__ == "__main__":
    main()